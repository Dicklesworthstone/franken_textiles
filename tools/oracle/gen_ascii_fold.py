#!/usr/bin/env python3
"""Generate crates/ftx-export/src/ascii_fold.tsv: what the reference's `ascii_text` keeps of each non-ASCII
code point (docs/spec/03 §2.2: NFKD, then × → x, — – · → -, then only code points 32..126).

NFKD of a string is the concatenation of its characters' decompositions (canonical reordering only moves
combining marks, which are dropped), so the projection is per character. Lines are `HEX<TAB>ASCII` for every
code point ≥ 0x80 whose projection is not empty; the header records the Unicode version. Run with the
reference's Python (3.12: Unicode 15.0.0):

    python gen_ascii_fold.py OUT.tsv
"""

from __future__ import annotations

import sys
import unicodedata


def project(c: str) -> str:
    s = unicodedata.normalize("NFKD", c)
    s = s.replace("×", "x").replace("—", "-").replace("–", "-").replace("·", "-")
    return "".join(ch for ch in s if 32 <= ord(ch) < 127)


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    lines = [f"# ascii_text projection, Unicode {unicodedata.unidata_version}; generated by tools/oracle/gen_ascii_fold.py"]
    for cp in range(0x80, 0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        p = project(chr(cp))
        if p:
            assert "\t" not in p and "\n" not in p
            lines.append(f"{cp:X}\t{p}")
    with open(argv[1], "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(lines) - 1} code points to {argv[1]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
