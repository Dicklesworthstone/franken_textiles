// OpenCV 4.13.0 predefined DICT_4X4_50: canonical row-major 4x4 data bits, 1 = white.
const MARKERS: [u16; 50] = [
    0xb532, 0x0f9a, 0x332d, 0x9946, 0x549e, 0x79cd, 0x9e2e, 0xc4f2, 0xfeda, 0xcf56, 0xf991, 0x11a7,
    0x0eb7, 0x2a0f, 0x24b1, 0x263e, 0x4665, 0x6600, 0x6c5e, 0x76af, 0x868b, 0xb02b, 0xccd5, 0xdd82,
    0xfe47, 0x9471, 0xace4, 0xa554, 0x2123, 0x346f, 0x4415, 0x57b2, 0x9ecf, 0xf0cb, 0x08ae, 0x0929,
    0x1875, 0x04ff, 0x0df6, 0x1c5a, 0x1718, 0x2a28, 0x328c, 0x38b2, 0x24e8, 0x2eeb, 0x2d3f, 0x4b64,
    0x502e, 0x5013,
];

const SEARCH_SIDE: usize = 1000;

fn refuse(msg: impl Into<String>) -> Refusal {
    Refusal::new(
        RefusalCode::Unscaled,
        format!("ChArUco detection refused: {}", msg.into()),
    )
    .repair("show one flat ChArUco board and use its original calib-sheet JSON sidecar")
}

struct BoardSpec {
    sx: usize,
    sy: usize,
    square_mm: f64,
    marker_mm: f64,
    legacy: bool,
    origin_mm: [f64; 2],
    paper: String,
}

fn parse_board(sheet: &Value) -> Result<BoardSpec, Refusal> {
    if sheet.get("schema").and_then(Value::as_str) != Some("fabric-calib-sheet/1") {
        return Err(refuse(
            "expected a fabric-calib-sheet/1 sidecar from ftx measure calib-sheet",
        ));
    }
    let Some(b) = sheet.get("board").and_then(Value::as_object) else {
        return Err(refuse("sheet.board.type must be charuco"));
    };
    if b.get("type").and_then(Value::as_str) != Some("charuco") {
        return Err(refuse("sheet.board.type must be charuco"));
    }
    const ALLOWED: &[&str] = &[
        "type",
        "dictionary",
        "squares_x",
        "squares_y",
        "square_mm",
        "marker_mm",
        "legacy_pattern",
        "origin_mm",
        "origin_px",
        "size_mm",
        "size_px",
        "png_scale",
        "frame",
    ];
    for k in b.keys() {
        if !ALLOWED.contains(&k.as_str()) {
            return Err(refuse(format!("unsupported board fields: {k}")));
        }
    }
    if b.get("dictionary").and_then(Value::as_str) != Some("DICT_4X4_50") {
        return Err(refuse(
            "unsupported dictionary; use the DICT_4X4_50 sheet generated by ftx",
        ));
    }
    let int_field = |key: &str| -> Result<usize, Refusal> {
        b.get(key)
            .and_then(Value::as_u64)
            .filter(|&v| (3..=64).contains(&v))
            .map(|v| v as usize)
            .ok_or_else(|| refuse(format!("{key} must be an integer in 3..=64")))
    };
    let sx = int_field("squares_x")?;
    let sy = int_field("squares_y")?;
    if (sx * sy) / 2 > 50 || (sx - 1) * (sy - 1) > 512 {
        return Err(refuse("board exceeds dictionary/corner capacity"));
    }
    let pos_field = |key: &str| -> Result<f64, Refusal> {
        b.get(key)
            .and_then(Value::as_f64)
            .filter(|v| v.is_finite() && *v > 0.0)
            .ok_or_else(|| refuse(format!("{key} must be finite and positive")))
    };
    let square_mm = pos_field("square_mm")?;
    let marker_mm = pos_field("marker_mm")?;
    if !(marker_mm < square_mm && square_mm <= 1000.0) {
        return Err(refuse("require 0 < marker_mm < square_mm <= 1000"));
    }
    let legacy = match b.get("legacy_pattern") {
        None => false,
        Some(Value::Bool(v)) => *v,
        Some(_) => return Err(refuse("legacy_pattern must be a boolean")),
    };
    let origin_mm = match b.get("origin_mm") {
        None => [0.0, 0.0],
        Some(Value::Array(a)) if a.len() == 2 => {
            let x = a[0]
                .as_f64()
                .filter(|v| v.is_finite())
                .ok_or_else(|| refuse("origin_mm must be two finite numbers"))?;
            let y = a[1]
                .as_f64()
                .filter(|v| v.is_finite())
                .ok_or_else(|| refuse("origin_mm must be two finite numbers"))?;
            [x, y]
        }
        Some(_) => return Err(refuse("origin_mm must be two finite numbers")),
    };
    if let Some(size) = b.get("size_mm") {
        let Some(a) = size.as_array().filter(|a| a.len() == 2) else {
            return Err(refuse(
                "size_mm disagrees with square_mm and board dimensions",
            ));
        };
        let sx_mm = a[0]
            .as_f64()
            .filter(|v| v.is_finite())
            .ok_or_else(|| refuse("size_mm disagrees with square_mm and board dimensions"))?;
        let sy_mm = a[1]
            .as_f64()
            .filter(|v| v.is_finite())
            .ok_or_else(|| refuse("size_mm disagrees with square_mm and board dimensions"))?;
        if (sx_mm - sx as f64 * square_mm).abs() > 1e-6
            || (sy_mm - sy as f64 * square_mm).abs() > 1e-6
        {
            return Err(refuse(
                "size_mm disagrees with square_mm and board dimensions",
            ));
        }
    }
    let paper = match sheet.get("paper").and_then(Value::as_str) {
        Some(p @ ("letter" | "a4")) => p.to_owned(),
        _ => return Err(refuse("sheet.paper must be letter or a4")),
    };
    Ok(BoardSpec {
        sx,
        sy,
        square_mm,
        marker_mm,
        legacy,
        origin_mm,
        paper,
    })
}

struct GrayImage {
    w: usize,
    h: usize,
    data: Vec<f64>,
}

impl GrayImage {
    fn from_bgr(bgr: &[u8], w: usize, h: usize) -> Self {
        let mut data = Vec::with_capacity(w * h);
        for px in bgr.chunks_exact(3) {
            let b = f64::from(px[0]);
            let g = f64::from(px[1]);
            let r = f64::from(px[2]);
            data.push(((b * 3735.0 + g * 19235.0 + r * 9798.0 + 16384.0) / 32768.0).floor());
        }
        Self { w, h, data }
    }

    fn sample(&self, p: Point) -> f64 {
        let x = p[0].clamp(0.0, (self.w - 1) as f64);
        let y = p[1].clamp(0.0, (self.h - 1) as f64);
        let (ix, iy) = (x as usize, y as usize);
        let (jx, jy) = ((ix + 1).min(self.w - 1), (iy + 1).min(self.h - 1));
        let (fx, fy) = (x - ix as f64, y - iy as f64);
        let r0 = self.data[iy * self.w + ix] * (1.0 - fx) + self.data[iy * self.w + jx] * fx;
        let r1 = self.data[jy * self.w + ix] * (1.0 - fx) + self.data[jy * self.w + jx] * fx;
        r0 * (1.0 - fy) + r1 * fy
    }

    fn downsample(&self, max_side: usize) -> (Self, f64, f64) {
        let s = (max_side as f64 / self.w.max(self.h) as f64).min(1.0);
        if s >= 1.0 {
            return (
                Self {
                    w: self.w,
                    h: self.h,
                    data: self.data.clone(),
                },
                1.0,
                1.0,
            );
        }
        let sw = ((self.w as f64 * s).round_ties_even() as usize).max(2);
        let sh = ((self.h as f64 * s).round_ties_even() as usize).max(2);
        let sx = self.w as f64 / sw as f64;
        let sy = self.h as f64 / sh as f64;
        let mut out = Vec::with_capacity(sw * sh);
        for y in 0..sh {
            let (y0, y1) = (y as f64 * sy, (y + 1) as f64 * sy);
            for x in 0..sw {
                let (x0, x1) = (x as f64 * sx, (x + 1) as f64 * sx);
                let mut acc = 0.0;
                for yy in y0.floor() as usize..(y1.ceil() as usize).min(self.h) {
                    let dy = (y1.min((yy + 1) as f64) - y0.max(yy as f64)).max(0.0);
                    for xx in x0.floor() as usize..(x1.ceil() as usize).min(self.w) {
                        let dx = (x1.min((xx + 1) as f64) - x0.max(xx as f64)).max(0.0);
                        acc += (dx * dy) * self.data[yy * self.w + xx];
                    }
                }
                out.push(acc / (sx * sy));
            }
        }
        (
            Self {
                w: sw,
                h: sh,
                data: out,
            },
            sx,
            sy,
        )
    }

    fn adaptive_dark(&self, radius: usize, offset: f64) -> Vec<u8> {
        let stride = self.w + 1;
        let mut integ = vec![0.0; (self.h + 1) * stride];
        for y in 0..self.h {
            let mut row_sum = 0.0;
            for x in 0..self.w {
                row_sum += self.data[y * self.w + x];
                integ[(y + 1) * stride + x + 1] = integ[y * stride + x + 1] + row_sum;
            }
        }
        let mut mask = vec![0_u8; self.w * self.h];
        for y in 0..self.h {
            let y0 = y.saturating_sub(radius);
            let y1 = (y + radius + 1).min(self.h);
            for x in 0..self.w {
                let x0 = x.saturating_sub(radius);
                let x1 = (x + radius + 1).min(self.w);
                let sum =
                    integ[y1 * stride + x1] - integ[y0 * stride + x1] - integ[y1 * stride + x0]
                        + integ[y0 * stride + x0];
                let mean = sum / ((x1 - x0) * (y1 - y0)) as f64;
                if self.data[y * self.w + x] + offset < mean {
                    mask[y * self.w + x] = 1;
                }
            }
        }
        mask
    }
}

fn sub(a: Point, b: Point) -> Point {
    [a[0] - b[0], a[1] - b[1]]
}
fn cross(a: Point, b: Point) -> f64 {
    a[0] * b[1] - a[1] * b[0]
}
fn poly_area(p: &[Point]) -> f64 {
    p.iter()
        .zip(p.iter().cycle().skip(1))
        .map(|(&a, &b)| cross(a, b))
        .sum::<f64>()
        * 0.5
}

fn convex_hull(mut pts: Vec<Point>) -> Vec<Point> {
    pts.sort_by(|a, b| a[0].total_cmp(&b[0]).then(a[1].total_cmp(&b[1])));
    pts.dedup();
    if pts.len() < 3 {
        return pts;
    }
    let build = |iter: &mut dyn Iterator<Item = Point>| -> Vec<Point> {
        let mut chain: Vec<Point> = Vec::new();
        for p in iter {
            while chain.len() >= 2
                && cross(
                    sub(chain[chain.len() - 1], chain[chain.len() - 2]),
                    sub(p, chain[chain.len() - 1]),
                ) <= 0.0
            {
                chain.pop();
            }
            chain.push(p);
        }
        chain.pop();
        chain
    };
    let mut out = build(&mut pts.iter().copied());
    out.extend(build(&mut pts.into_iter().rev()));
    out
}

fn hull_to_quad(hull: &[Point]) -> Option<[Point; 4]> {
    if hull.len() < 4 {
        return None;
    }
    let full_area = poly_area(hull).abs();
    if full_area < 64.0 {
        return None;
    }
    let mut poly = hull.to_vec();
    while poly.len() > 4 {
        let n = poly.len();
        let mut best_i = 0;
        let mut best_loss = f64::INFINITY;
        for i in 0..n {
            let prev = poly[(i + n - 1) % n];
            let curr = poly[i];
            let next = poly[(i + 1) % n];
            let loss = cross(sub(curr, prev), sub(next, prev)).abs();
            if loss < best_loss {
                best_loss = loss;
                best_i = i;
            }
        }
        poly.remove(best_i);
    }
    let mut quad = [poly[0], poly[1], poly[2], poly[3]];
    if poly_area(&quad) < 0.0 {
        quad.reverse();
    }
    let q_area = poly_area(&quad);
    if q_area < 0.78 * full_area || !convex_clockwise(&quad) {
        return None;
    }
    Some(quad)
}

fn fit_line(pts: &[Point]) -> Option<[f64; 3]> {
    if pts.len() < 4 {
        return None;
    }
    let n = pts.len() as f64;
    let mx = pts.iter().map(|p| p[0]).sum::<f64>() / n;
    let my = pts.iter().map(|p| p[1]).sum::<f64>() / n;
    let mut sxx = 0.0;
    let mut sxy = 0.0;
    let mut syy = 0.0;
    for p in pts {
        let dx = p[0] - mx;
        let dy = p[1] - my;
        sxx += dx * dx;
        sxy += dx * dy;
        syy += dy * dy;
    }
    let trace = sxx + syy;
    let det_m = sxx * syy - sxy * sxy;
    let disc = (0.25 * trace * trace - det_m).max(0.0).sqrt();
    let lambda_min = 0.5 * trace - disc;
    let (nx, ny) = if sxy.abs() > 1e-9 {
        (sxy, lambda_min - sxx)
    } else if sxx <= syy {
        (1.0, 0.0)
    } else {
        (0.0, 1.0)
    };
    let norm = det::hypot(nx, ny);
    if norm <= 1e-12 {
        return None;
    }
    let (a, b) = (nx / norm, ny / norm);
    let c = -(a * mx + b * my);
    Some([a, b, c])
}

fn intersect_lines(l1: [f64; 3], l2: [f64; 3]) -> Option<Point> {
    let det = l1[0] * l2[1] - l1[1] * l2[0];
    if det.abs() < 1e-9 {
        return None;
    }
    Some([
        (l1[1] * l2[2] - l2[1] * l1[2]) / det,
        (l2[0] * l1[2] - l1[0] * l2[2]) / det,
    ])
}

fn refine_marker_quad(gray: &GrayImage, coarse: [Point; 4]) -> Option<[Point; 4]> {
    let mut lines = [[0.0; 3]; 4];
    for s in 0..4 {
        let a = coarse[s];
        let b = coarse[(s + 1) % 4];
        let d = sub(b, a);
        let len = det::hypot(d[0], d[1]);
        if len < 12.0 {
            return None;
        }
        let t = [d[0] / len, d[1] / len];
        // For a clockwise quad on screen (+x right, +y down), [-ty, tx] points inward into the black border.
        let n_in = [-t[1], t[0]];
        let r_max = (len * 0.10).clamp(3.0, 12.0);
        let steps = (2.0 * r_max).round() as isize;
        let mut pts = Vec::with_capacity(15);
        for k in 0..15 {
            let tau = 0.16 + 0.68 * (k as f64 / 14.0);
            let base = [a[0] + tau * d[0], a[1] + tau * d[1]];
            let drop_at = |u: f64| -> f64 {
                let p_out = [base[0] + (u - 0.5) * n_in[0], base[1] + (u - 0.5) * n_in[1]];
                let p_in = [base[0] + (u + 0.5) * n_in[0], base[1] + (u + 0.5) * n_in[1]];
                gray.sample(p_out) - gray.sample(p_in)
            };
            let mut best_u = 0.0;
            let mut best_drop = f64::NEG_INFINITY;
            for step in -steps..=steps {
                let u = step as f64 * 0.5;
                let dr = drop_at(u);
                if dr > best_drop {
                    best_drop = dr;
                    best_u = u;
                }
            }
            if best_drop < 15.0 {
                continue;
            }
            let mut num = 0.0;
            let mut den = 0.0;
            for du in [-1.0, -0.5, 0.0, 0.5, 1.0] {
                let u = best_u + du;
                let w = drop_at(u).max(0.0).powi(2);
                num += w * u;
                den += w;
            }
            let u_ref = if den > 1e-9 { num / den } else { best_u };
            pts.push([base[0] + u_ref * n_in[0], base[1] + u_ref * n_in[1]]);
        }
        let line0 = fit_line(&pts)?;
        // Trim up to 2 worst residuals and refit.
        let mut indexed: Vec<(f64, Point)> = pts
            .into_iter()
            .map(|p| ((line0[0] * p[0] + line0[1] * p[1] + line0[2]).abs(), p))
            .collect();
        indexed.sort_by(|a, b| a.0.total_cmp(&b.0));
        let keep = indexed.len().saturating_sub(2).max(4);
        let trimmed: Vec<Point> = indexed.into_iter().take(keep).map(|(_, p)| p).collect();
        lines[s] = fit_line(&trimmed)?;
    }
    let mut refined = [[0.0; 2]; 4];
    for s in 0..4 {
        let p = intersect_lines(lines[(s + 3) % 4], lines[s])?;
        if p[0] < 0.0 || p[0] > (gray.w - 1) as f64 || p[1] < 0.0 || p[1] > (gray.h - 1) as f64 {
            return None;
        }
        refined[s] = p;
    }
    if !convex_clockwise(&refined) {
        return None;
    }
    Some(refined)
}

#[derive(Clone, Copy, Debug)]
struct DetectedMarker {
    id: usize,
    corners: [Point; 4],
}

fn decode_marker_quad(gray: &GrayImage, quad: [Point; 4]) -> Option<DetectedMarker> {
    let unit = [[0.0, 0.0], [6.0, 0.0], [6.0, 6.0], [0.0, 6.0]];
    let h = fit(&unit, &quad).ok()?;
    let sample_cell = |u: f64, v: f64| -> Option<f64> {
        let mut sum = 0.0;
        for dv in [-0.15, 0.0, 0.15] {
            for du in [-0.15, 0.0, 0.15] {
                let p = h.map([u + du, v + dv]).ok()?;
                if p[0] < 0.0
                    || p[0] > (gray.w - 1) as f64
                    || p[1] < 0.0
                    || p[1] > (gray.h - 1) as f64
                {
                    return None;
                }
                sum += gray.sample(p);
            }
        }
        Some(sum / 9.0)
    };
    let mut margin_vals = Vec::with_capacity(16);
    for t in [1.0, 2.5, 3.5, 5.0] {
        for uv in [[-0.45, t], [6.45, t], [t, -0.45], [t, 6.45]] {
            let p = h.map(uv).ok()?;
            if p[0] >= 0.0
                && p[0] <= (gray.w - 1) as f64
                && p[1] >= 0.0
                && p[1] <= (gray.h - 1) as f64
            {
                margin_vals.push(gray.sample(p));
            }
        }
    }
    if margin_vals.len() < 12 {
        return None;
    }
    let mut border_vals = Vec::with_capacity(20);
    for r in 0..6 {
        for c in 0..6 {
            if r == 0 || r == 5 || c == 0 || c == 5 {
                border_vals.push(sample_cell(c as f64 + 0.5, r as f64 + 0.5)?);
            }
        }
    }
    let white_mean = margin_vals.iter().sum::<f64>() / margin_vals.len() as f64;
    let black_mean = border_vals.iter().sum::<f64>() / border_vals.len() as f64;
    let contrast = white_mean - black_mean;
    if contrast < 30.0 {
        return None;
    }
    let thresh = 0.5 * (white_mean + black_mean);
    let dark_borders = border_vals.iter().filter(|&&v| v < thresh).count();
    let bright_margins = margin_vals.iter().filter(|&&v| v > thresh).count();
    if dark_borders < 19 || bright_margins + 2 < margin_vals.len() {
        return None;
    }
    let mut cells = [[0.0; 4]; 4];
    let mut strong_bits = 0;
    for r in 0..4 {
        for c in 0..4 {
            let v = sample_cell((c + 1) as f64 + 0.5, (r + 1) as f64 + 0.5)?;
            cells[r][c] = v;
            if (v - thresh).abs() >= 0.12 * contrast {
                strong_bits += 1;
            }
        }
    }
    if strong_bits < 14 {
        return None;
    }
    let mut best_match: Option<(u32, usize, usize)> = None;
    let mut second_dist = 16_u32;
    for shift in 0..4 {
        let mut word = 0_u16;
        for r in 0..4 {
            for c in 0..4 {
                let val = match shift {
                    0 => cells[r][c],
                    1 => cells[c][3 - r],
                    2 => cells[3 - r][3 - c],
                    _ => cells[3 - c][r],
                };
                if val > thresh {
                    let bit = r * 4 + c;
                    word |= 1 << (15 - bit);
                }
            }
        }
        for (id, &code) in MARKERS.iter().enumerate() {
            let dist = (word ^ code).count_ones();
            if best_match.is_none_or(|(b_dist, _, _)| dist < b_dist) {
                if let Some((b_dist, _, _)) = best_match {
                    second_dist = second_dist.min(b_dist);
                }
                best_match = Some((dist, id, shift));
            } else {
                second_dist = second_dist.min(dist);
            }
        }
    }
    let (dist, id, shift) = best_match?;
    if dist > 1 || (dist == 1 && (strong_bits < 16 || second_dist <= 2)) {
        return None;
    }
    let corners = [
        quad[shift],
        quad[(shift + 1) % 4],
        quad[(shift + 2) % 4],
        quad[(shift + 3) % 4],
    ];
    Some(DetectedMarker { id, corners })
}

fn find_candidate_quads(gray: &GrayImage) -> Vec<[Point; 4]> {
    let (search, sx, sy) = gray.downsample(SEARCH_SIDE);
    let min_perim = 0.01 * (search.w.max(search.h) as f64);
    let mut out = Vec::new();
    for radius in [35, 18] {
        let mask = search.adaptive_dark(radius, 8.0);
        let mut seen = vec![0_u8; search.w * search.h];
        let mut queue = Vec::new();
        for start_y in 1..search.h - 1 {
            for start_x in 1..search.w - 1 {
                let start_idx = start_y * search.w + start_x;
                if mask[start_idx] == 0 || seen[start_idx] != 0 {
                    continue;
                }
                seen[start_idx] = 1;
                queue.clear();
                queue.push((start_x, start_y));
                let (mut min_x, mut max_x) = (start_x, start_x);
                let (mut min_y, mut max_y) = (start_y, start_y);
                let mut boundary = Vec::new();
                let mut head = 0;
                while head < queue.len() {
                    let (x, y) = queue[head];
                    head += 1;
                    min_x = min_x.min(x);
                    max_x = max_x.max(x);
                    min_y = min_y.min(y);
                    max_y = max_y.max(y);
                    let mut is_border = false;
                    for (nx, ny) in [
                        (x.wrapping_sub(1), y),
                        (x + 1, y),
                        (x, y.wrapping_sub(1)),
                        (x, y + 1),
                    ] {
                        if nx >= search.w || ny >= search.h {
                            is_border = true;
                            continue;
                        }
                        let nidx = ny * search.w + nx;
                        if mask[nidx] == 0 {
                            is_border = true;
                        } else if seen[nidx] == 0 {
                            seen[nidx] = 1;
                            queue.push((nx, ny));
                        }
                    }
                    if is_border {
                        boundary.push([x as f64, y as f64]);
                    }
                }
                if min_x == 0 || min_y == 0 || max_x >= search.w - 1 || max_y >= search.h - 1 {
                    continue;
                }
                let bw = max_x - min_x + 1;
                let bh = max_y - min_y + 1;
                if bw < 10
                    || bh < 10
                    || bw > search.w / 2
                    || bh > search.h / 2
                    || (bw + bh) * 2 < min_perim as usize
                {
                    continue;
                }
                let hull = convex_hull(boundary);
                let Some(quad_s) = hull_to_quad(&hull) else {
                    continue;
                };
                let quad_full = quad_s.map(|p| [(p[0] + 0.5) * sx - 0.5, (p[1] + 0.5) * sy - 0.5]);
                if let Some(refined) = refine_marker_quad(gray, quad_full) {
                    out.push(refined);
                } else {
                    out.push(quad_full);
                }
            }
        }
    }
    out
}

fn marker_board_coords(spec: &BoardSpec) -> Vec<(usize, usize, [Point; 4])> {
    let inset = 0.5 * (spec.square_mm - spec.marker_mm);
    let mut out = Vec::new();
    for row in 0..spec.sy {
        for col in 0..spec.sx {
            if (row + col) % 2 == usize::from(spec.legacy) {
                continue;
            }
            let x0 = col as f64 * spec.square_mm + inset;
            let x1 = (col + 1) as f64 * spec.square_mm - inset;
            let y0 = row as f64 * spec.square_mm + inset;
            let y1 = (row + 1) as f64 * spec.square_mm - inset;
            out.push((col, row, [[x0, y0], [x1, y0], [x1, y1], [x0, y1]]));
        }
    }
    out
}

fn corner_sub_pix(gray: &GrayImage, p0: Point, win: isize) -> Point {
    let sigma = (win as f64 * 0.5).max(1.0);
    let inv_two_sigma2 = 1.0 / (2.0 * sigma * sigma);
    let mut p = p0;
    for _ in 0..30 {
        if p[0] < (win + 1) as f64
            || p[0] > (gray.w as isize - win - 2) as f64
            || p[1] < (win + 1) as f64
            || p[1] > (gray.h as isize - win - 2) as f64
        {
            return p0;
        }
        let mut gxx = 0.0;
        let mut gxy = 0.0;
        let mut gyy = 0.0;
        let mut bx = 0.0;
        let mut by = 0.0;
        for dy in -win..=win {
            for dx in -win..=win {
                let x = p[0] + dx as f64;
                let y = p[1] + dy as f64;
                let w = det::exp(-((dx * dx + dy * dy) as f64) * inv_two_sigma2);
                let gx = 0.5 * (gray.sample([x + 1.0, y]) - gray.sample([x - 1.0, y]));
                let gy = 0.5 * (gray.sample([x, y + 1.0]) - gray.sample([x, y - 1.0]));
                let wx2 = w * gx * gx;
                let wxy = w * gx * gy;
                let wy2 = w * gy * gy;
                gxx += wx2;
                gxy += wxy;
                gyy += wy2;
                bx += wx2 * x + wxy * y;
                by += wxy * x + wy2 * y;
            }
        }
        let det_m = gxx * gyy - gxy * gxy;
        let trace = gxx + gyy;
        if det_m <= 1e-6 * trace * trace {
            break;
        }
        let nx = (gyy * bx - gxy * by) / det_m;
        let ny = (gxx * by - gxy * bx) / det_m;
        if det::hypot(nx - p0[0], ny - p0[1]) > win as f64 {
            return p0;
        }
        let step = det::hypot(nx - p[0], ny - p[1]);
        p = [nx, ny];
        if step < 1e-3 {
            break;
        }
    }
    p
}

/// Detect `DICT_4X4_50` ArUco markers and subpixel ChArUco chessboard corners in pure Rust.
///
/// Returns the `ftx-charuco-detection/1` JSON envelope consumed by the photo scale and pose
/// pipelines.
pub fn detect_charuco(
    bgr: &[u8],
    w: usize,
    h: usize,
    sheet: &Value,
    intrinsics: Option<Intrinsics>,
) -> Result<Value, Refusal> {
    let spec = parse_board(sheet)?;
    if !(2..=1_000_000).contains(&w)
        || !(2..=1_000_000).contains(&h)
        || w.checked_mul(h).is_none_or(|n| n > super::MAX_PHOTO_PIXELS)
    {
        return Err(refuse("invalid or oversized image_size_px"));
    }
    if bgr.len() != w * h * 3 {
        return Err(refuse("BGR input length disagrees with image_size_px"));
    }
    if let Some(k) = &intrinsics {
        k.validate()?;
    }
    let gray = GrayImage::from_bgr(bgr, w, h);
    let board_markers = marker_board_coords(&spec);
    let max_id = board_markers.len();

    let mut by_id: Vec<Option<DetectedMarker>> = vec![None; 50];
    for quad in find_candidate_quads(&gray) {
        let Some(m) = decode_marker_quad(&gray, quad) else {
            continue;
        };
        if m.id >= max_id {
            return Err(refuse(
                "BOARD_MISMATCH: detected marker IDs do not belong to this sidecar",
            ));
        }
        if let Some(prev) = &by_id[m.id] {
            let c_prev = [
                0.25 * prev.corners.iter().map(|p| p[0]).sum::<f64>(),
                0.25 * prev.corners.iter().map(|p| p[1]).sum::<f64>(),
            ];
            let c_now = [
                0.25 * m.corners.iter().map(|p| p[0]).sum::<f64>(),
                0.25 * m.corners.iter().map(|p| p[1]).sum::<f64>(),
            ];
            let diag = det::hypot(
                prev.corners[2][0] - prev.corners[0][0],
                prev.corners[2][1] - prev.corners[0][1],
            );
            if det::hypot(c_now[0] - c_prev[0], c_now[1] - c_prev[1]) > 0.35 * diag {
                return Err(refuse(
                    "AMBIGUOUS_BOARD: duplicate marker IDs; show only one calibration board",
                ));
            }
        } else {
            by_id[m.id] = Some(m);
        }
    }

    // Refine/recover missed markers using the initial board-to-image homography when >= 2 markers exist.
    let initial_ids: Vec<usize> = by_id
        .iter()
        .enumerate()
        .filter_map(|(id, m)| m.as_ref().map(|_| id))
        .collect();
    if initial_ids.len() >= 2 {
        let mut board_pts = Vec::with_capacity(initial_ids.len() * 4);
        let mut img_pts = Vec::with_capacity(initial_ids.len() * 4);
        for &id in &initial_ids {
            let m = by_id[id].as_ref().unwrap();
            let (_, _, b_quad) = board_markers[id];
            for k in 0..4 {
                board_pts.push(b_quad[k]);
                img_pts.push(undistort_point(m.corners[k], intrinsics.as_ref())?);
            }
        }
        if let Ok(h_board_to_px) = fit(&board_pts, &img_pts) {
            for (id, &(_, _, b_quad)) in board_markers.iter().enumerate() {
                if by_id[id].is_some() {
                    continue;
                }
                let mut proj = [[0.0; 2]; 4];
                let mut ok = true;
                for k in 0..4 {
                    if let Ok(u) = h_board_to_px.map(b_quad[k])
                        && let Ok(p) = distort_point(u, intrinsics.as_ref())
                        && p[0] >= 4.0
                        && p[0] <= (w - 5) as f64
                        && p[1] >= 4.0
                        && p[1] <= (h - 5) as f64
                    {
                        proj[k] = p;
                    } else {
                        ok = false;
                        break;
                    }
                }
                if !ok {
                    continue;
                }
                let candidate = refine_marker_quad(&gray, proj).unwrap_or(proj);
                if let Some(m) = decode_marker_quad(&gray, candidate)
                    && m.id == id
                {
                    by_id[id] = Some(m);
                }
            }
        }
    }

    let marker_ids: Vec<usize> = by_id
        .iter()
        .enumerate()
        .filter_map(|(id, m)| m.as_ref().map(|_| id))
        .collect();
    let mut detections: Vec<(usize, Point)> = Vec::new();
    if marker_ids.len() >= 2 {
        let all_marker_vertices: Vec<Point> = marker_ids
            .iter()
            .flat_map(|&id| by_id[id].as_ref().unwrap().corners)
            .collect();
        for gy in 1..spec.sy {
            for gx in 1..spec.sx {
                let corner_id = (gy - 1) * (spec.sx - 1) + (gx - 1);
                // Require at least 1 immediately adjacent marker and >= 2 markers within 2 squares.
                let mut adj_count = 0;
                let mut local_board = Vec::new();
                let mut local_img = Vec::new();
                for &id in &marker_ids {
                    let (mcol, mrow, b_quad) = board_markers[id];
                    let dx = (mcol as isize - gx as isize).max(gx as isize - 1 - mcol as isize);
                    let dy = (mrow as isize - gy as isize).max(gy as isize - 1 - mrow as isize);
                    if dx == 0 && dy == 0 {
                        adj_count += 1;
                    }
                    if dx <= 1 && dy <= 1 {
                        let m = by_id[id].as_ref().unwrap();
                        for k in 0..4 {
                            local_board.push(b_quad[k]);
                            local_img.push(undistort_point(m.corners[k], intrinsics.as_ref())?);
                        }
                    }
                }
                if adj_count == 0 || local_board.len() < 8 {
                    continue;
                }
                let Ok(h_local) = fit(&local_board, &local_img) else {
                    continue;
                };
                let target_mm = [gx as f64 * spec.square_mm, gy as f64 * spec.square_mm];
                let Ok(u0) = h_local.map(target_mm) else {
                    continue;
                };
                let Ok(p0) = distort_point(u0, intrinsics.as_ref()) else {
                    continue;
                };
                if p0[0] < 3.0 || p0[0] > (w - 4) as f64 || p0[1] < 3.0 || p0[1] > (h - 4) as f64 {
                    continue;
                }
                // Verify the 4 checkerboard quadrants around (gx, gy) within the pure-inset zone.
                let delta_mm = 0.45 * (spec.square_mm - spec.marker_mm);
                let mut black_quads = Vec::with_capacity(2);
                let mut white_quads = Vec::with_capacity(2);
                let mut quad_ok = true;
                for (qcol, qrow, sx_sign, sy_sign) in [
                    (gx - 1, gy - 1, -1.0, -1.0),
                    (gx, gy - 1, 1.0, -1.0),
                    (gx, gy, 1.0, 1.0),
                    (gx - 1, gy, -1.0, 1.0),
                ] {
                    let q_mm = [
                        target_mm[0] + sx_sign * delta_mm,
                        target_mm[1] + sy_sign * delta_mm,
                    ];
                    let Ok(qu) = h_local.map(q_mm) else {
                        quad_ok = false;
                        break;
                    };
                    let Ok(qp) = distort_point(qu, intrinsics.as_ref()) else {
                        quad_ok = false;
                        break;
                    };
                    if qp[0] < 1.0
                        || qp[0] > (w - 2) as f64
                        || qp[1] < 1.0
                        || qp[1] > (h - 2) as f64
                    {
                        quad_ok = false;
                        break;
                    }
                    let val = gray.sample(qp);
                    let is_black = (qrow + qcol) % 2 == usize::from(spec.legacy);
                    if is_black {
                        black_quads.push(val);
                    } else {
                        white_quads.push(val);
                    }
                }
                if !quad_ok {
                    continue;
                }
                let min_white = white_quads.into_iter().fold(f64::INFINITY, f64::min);
                let max_black = black_quads.into_iter().fold(f64::NEG_INFINITY, f64::max);
                if min_white - max_black < 25.0 {
                    continue;
                }
                let min_dist = all_marker_vertices
                    .iter()
                    .map(|v| det::hypot(v[0] - p0[0], v[1] - p0[1]))
                    .fold(f64::INFINITY, f64::min);
                let win = (min_dist * 0.5).floor().clamp(1.0, 5.0) as isize;
                let refined = corner_sub_pix(&gray, p0, win);
                if refined[0] >= 0.0
                    && refined[0] <= (w - 1) as f64
                    && refined[1] >= 0.0
                    && refined[1] <= (h - 1) as f64
                {
                    detections.push((corner_id, refined));
                }
            }
        }
    }

    let corners: Vec<Value> = detections
        .into_iter()
        .map(|(id, p)| json!({"id": id, "point_px": p}))
        .collect();
    let reference = json!({
        "schema": "ftx-photo-reference/1",
        "reference": "charuco",
        "image_size_px": [w, h],
        "paper": spec.paper,
        "board": {
            "squares_x": spec.sx,
            "squares_y": spec.sy,
            "square_mm": spec.square_mm,
            "origin_mm": spec.origin_mm,
        },
        "corners": corners,
        "markers_detected": marker_ids.len(),
    });
    Ok(json!({
        "schema": "ftx-charuco-detection/1",
        "reference": reference,
        "detector": {
            "backend": "rust_charuco",
            "dictionary": "DICT_4X4_50",
            "legacy_pattern": spec.legacy,
            "marker_ids": marker_ids,
            "min_marker_perimeter_rate": 0.01,
            "min_markers_per_corner": 2,
            "refine_markers": true,
            "chessboard_refinement": "adaptive_cornerSubPix",
            "uses_lens_intrinsics": intrinsics.is_some(),
            "threads": 1,
            "coordinate_frame": "stored_full_resolution_pixels",
        }
    }))
}
