//! Pure-Rust `DICT_4X4_50` ArUco marker and ChArUco subpixel chessboard corner detector.
//!
//! Operates on full-resolution, EXIF-oriented BGR pixels and a `fabric-calib-sheet/1` sidecar.
//! No external process, Python runtime or OpenCV installation is required.

use ftx_core::{Refusal, RefusalCode, det};
use serde_json::{Value, json};

use crate::camera::Intrinsics;

