//! Synthetic inverse-problem checks. Generated forces verify identification software, not
//! empirical accuracy; independent analytic mechanics answers live in strip_experiment.rs.

use std::{collections::BTreeMap, sync::OnceLock};

use ftx_core::RefusalCode;
use ftx_drape::strip::{
    Controls, Fixture, Request, evaluate,
    fit::{Experiment, Input, Observation, Policy, Report, Width, calibrate},
    solve,
};
use ftx_pattern::{
    material_calibration::Partition,
    materials::{Evidence, Form, Material, Source},
};

const PARAMETERS: [f64; 4] = [300.0, 180.0, 0.2, 70.0];

fn controls() -> Controls {
    Controls {
        tolerance_m: 1e-9,
        force_tolerance_n: 1e-6,
        max_newton: 100,
    }
}

fn fixture(axis: [f64; 2]) -> Fixture {
    Fixture {
        gauge_length_m: 0.1,
        width_m: 0.06,
        warp_axis: axis,
        cells: [2, 2],
    }
}

fn observation(id: &str, fixture: &Fixture, extension: f64) -> Observation {
    let state = solve(fixture, PARAMETERS, extension, &controls()).unwrap();
    Observation {
        id: id.into(),
        extension_fraction: extension,
        force_n: state.force_n,
        scale_n: 0.1,
        mid_width: Some(Width {
            value_m: state.mid_width_m,
            scale_m: 0.001,
        }),
    }
}

fn input() -> Input {
    let mut sources = BTreeMap::new();
    let mut experiments = Vec::new();
    let bias = std::f64::consts::FRAC_1_SQRT_2;
    for (id, axis, partition, extensions) in [
        ("fit-warp", [0.0, 1.0], Partition::Fit, vec![0.04, 0.08]),
        ("fit-weft", [1.0, 0.0], Partition::Fit, vec![0.04, 0.08]),
        ("fit-bias", [bias, bias], Partition::Fit, vec![0.04, 0.08]),
        ("check-warp", [0.0, 1.0], Partition::Check, vec![0.03]),
    ] {
        let fixture = fixture(axis);
        let observations = extensions
            .into_iter()
            .enumerate()
            .map(|(i, extension)| observation(&format!("{id}-{i}"), &fixture, extension))
            .collect();
        sources.insert(id.into(), Source {
            reference: format!("test:synthetic-clamped-strip/{id}"),
            accessed_on: "2026-10-21".into(),
            note: "Generated by the production strip solver from [300,180,0.2,70]; numerical test data, no measured textile or empirical independence claim".into(),
        });
        experiments.push(Experiment {
            id: id.into(),
            fixture,
            source: id.into(),
            evidence: Evidence::Estimate,
            partition,
            observations,
        });
    }
    Input {
        schema: "ftx-strip-calibration/1".into(),
        material: Material {
            id: "synthetic-identified-strip".into(),
            name: "Synthetic inverse strip software fixture, not a real textile".into(),
            form: Form::Woven,
            composition: vec![], composition_complete: false,
            structure: BTreeMap::new(), properties: BTreeMap::new(),
            membrane_response: None, membrane_relaxation: None, thermal_response: None,
            optical_faces: None, sources,
        },
        method: "Synthetic ideal full-width no-slip planar grips; 100 mm gauge, 60 mm width, independent elastic loading states; no actual specimen or conditioning".into(),
        conditions: BTreeMap::from([("provenance".into(), "synthetic solver-generated regression".into())]),
        fitted_on: "2026-10-21".into(),
        experiments,
        parameter_bounds: [[200.0, 400.0], [100.0, 260.0], [0.05, 0.35], [40.0, 100.0]],
        response_family: None,
        admit_planar_elastic_model: true,
        allow_estimated_observations: true,
        replace_existing: false,
        allow_estimates: true,
        controls: controls(),
        policy: Policy {
            max_rms_scaled: 1.0,
            max_peak_scaled: 1.0,
            max_mesh_scaled: 1.0,
            min_excitation_pivot: 1e-4,
            max_iterations: 40,
            max_forward_solves: 8000,
        },
    }
}

fn baseline() -> &'static Report {
    static REPORT: OnceLock<Report> = OnceLock::new();
    REPORT.get_or_init(|| calibrate(&input()).unwrap())
}

#[test]
fn identifies_four_coefficients_from_actual_clamps_and_replays_frozen_domain() {
    let report = baseline();
    assert!(report.accepted, "{:#?}", report.reasons);
    assert!(report.domain_replay_verified);
    for (actual, expected) in report.parameters.iter().zip(PARAMETERS) {
        assert!(
            (actual - expected).abs() < 1e-3 * expected,
            "{actual} != {expected}"
        );
    }
    assert!(report.starts.iter().all(|s| s.converged));
    assert!(report.excitation_pivot >= report.input.policy.min_excitation_pivot);
    assert_eq!(report.fit.components, 12);
    assert_eq!(report.check.as_ref().unwrap().components, 2);
    let material = report.material.as_ref().unwrap();
    assert_eq!(material.properties.len(), 4);
    assert!(
        material
            .properties
            .values()
            .all(|q| q.evidence == Evidence::Estimate)
    );
    assert!(
        material.mechanics(true).is_err(),
        "unidentified mass/bending/contact must stay absent"
    );
    let selection = report.selection.as_ref().unwrap();
    assert!(selection.expected_sha256.is_some());
    assert_eq!(
        report.selection_json.as_deref().unwrap(),
        serde_json::to_string(selection).unwrap()
    );
    for experiment in &report.input.experiments {
        for factor in [1, 2] {
            let mut fixture = experiment.fixture.clone();
            fixture.cells.iter_mut().for_each(|n| *n *= factor);
            let result = evaluate(&Request {
                schema: "ftx-strip-experiment/1".into(),
                material: selection.clone(),
                fixture,
                extensions: experiment
                    .observations
                    .iter()
                    .map(|o| o.extension_fraction)
                    .collect(),
                controls: controls(),
            })
            .unwrap_or_else(|error| panic!("{} mesh factor {factor}: {error:?}", experiment.id));
            assert!(result.states.iter().all(|s| s.free_force_residual_n < 1e-6));
        }
    }
}

#[test]
fn held_out_errors_cannot_change_coefficients_and_never_publish_a_bad_fit() {
    let expected = baseline();
    let mut changed = input();
    changed.experiments.last_mut().unwrap().observations[0].force_n += 10.0;
    let report = calibrate(&changed).unwrap();
    assert!(!report.accepted);
    assert!(
        report.material.is_none() && report.selection.is_none() && report.selection_json.is_none()
    );
    assert_eq!(report.parameters, expected.parameters);
    assert_eq!(
        report.starts.iter().map(|s| s.fit_sse).collect::<Vec<_>>(),
        expected
            .starts
            .iter()
            .map(|s| s.fit_sse)
            .collect::<Vec<_>>()
    );
    assert!(
        report
            .reasons
            .iter()
            .any(|r| r.contains("CHECK force/width"))
    );
    assert!(report.check.unwrap().peak_scaled > 90.0);
}

#[test]
fn check_first_outside_fit_domain_refuses_without_widening_fit_envelope() {
    let expected = baseline();
    let mut changed = input();
    let check = changed.experiments.last_mut().unwrap();
    check.observations = vec![observation("outside-fit", &check.fixture, 0.2)];
    changed.experiments.rotate_right(1);
    changed.policy.max_rms_scaled = 1e6;
    changed.policy.max_peak_scaled = 1e6;
    changed.policy.max_mesh_scaled = 1e6;
    let report = calibrate(&changed).unwrap();
    assert_eq!(report.parameters, expected.parameters);
    assert_eq!(
        report.fitted_green_strain_range,
        expected.fitted_green_strain_range
    );
    assert!(!report.accepted);
    assert!(
        report
            .reasons
            .iter()
            .any(|r| r.contains("FIT-only local strain domain"))
    );
}

#[test]
fn missing_check_and_mesh_error_keep_diagnostics_without_materials() {
    let mut absent = input();
    absent.experiments.retain(|e| e.partition == Partition::Fit);
    let report = calibrate(&absent).unwrap();
    assert!(report.check.is_none() && report.material.is_none());
    assert!(
        report
            .reasons
            .iter()
            .any(|r| r.contains("independent held-out CHECK"))
    );
    let mut coarse = input();
    coarse.policy.max_mesh_scaled = 1e-12;
    let report = calibrate(&coarse).unwrap();
    assert!(!report.accepted);
    assert!(report.mesh_change_peak_scaled > 1e-6);
    assert!(
        report
            .reasons
            .iter()
            .any(|r| r.contains("doubling the strip mesh"))
    );
}

#[test]
fn malformed_evidence_and_aggregate_work_refuse_before_publication() {
    let mut raw = input();
    raw.allow_estimated_observations = false;
    assert!(calibrate(&raw).is_err());
    raw = input();
    raw.experiments.last_mut().unwrap().source = "fit-warp".into();
    assert!(
        calibrate(&raw)
            .unwrap_err()
            .message
            .contains("same source acquisition")
    );
    raw = input();
    raw.parameter_bounds[2] = [0.05, 2.0];
    assert!(calibrate(&raw).is_err());
    raw = input();
    raw.policy.max_forward_solves = 1;
    assert_eq!(
        calibrate(&raw).unwrap_err().code,
        RefusalCode::BudgetExceeded
    );
    raw = input();
    raw.admit_planar_elastic_model = false;
    assert!(calibrate(&raw).is_err());
    raw = input();
    for (i, point) in raw.experiments[0].observations.iter_mut().enumerate() {
        point.extension_fraction = if i == 0 { 0.0 } else { -0.0 };
    }
    assert!(calibrate(&raw).is_err());
}
