//! Generate an explicitly synthetic inverse request using the actual production strip solver.
//! `cargo run -p ftx-drape --example strip_fixture > NEW-REQUEST.json`
//! The observations are software-test outputs, not measurements of a textile or physical replicate.

use std::collections::BTreeMap;

use ftx_drape::strip::{
    Controls, Fixture,
    fit::{Experiment, Input, Observation, Policy, Width},
    solve,
};
use ftx_pattern::{
    material_calibration::Partition,
    materials::{Evidence, Form, Material, Source},
};

const PARAMETERS: [f64; 4] = [300.0, 180.0, 0.2, 70.0];

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let controls = Controls {
        tolerance_m: 1e-9,
        force_tolerance_n: 1e-6,
        max_newton: 100,
    };
    let mut sources = BTreeMap::new();
    let mut experiments = Vec::new();
    let bias = std::f64::consts::FRAC_1_SQRT_2;
    for (id, axis, partition, extensions) in [
        ("fit-warp", [0.0, 1.0], Partition::Fit, vec![0.04, 0.08]),
        ("fit-weft", [1.0, 0.0], Partition::Fit, vec![0.04, 0.08]),
        ("fit-bias", [bias, bias], Partition::Fit, vec![0.04, 0.08]),
        ("check-warp", [0.0, 1.0], Partition::Check, vec![0.03]),
    ] {
        let fixture = Fixture {
            gauge_length_m: 0.1,
            width_m: 0.06,
            warp_axis: axis,
            cells: [2, 2],
        };
        let mut observations = Vec::new();
        for (i, extension) in extensions.into_iter().enumerate() {
            let state = solve(&fixture, PARAMETERS, extension, &controls)?;
            observations.push(Observation {
                id: format!("{id}-{i}"),
                extension_fraction: extension,
                force_n: state.force_n,
                scale_n: 0.1,
                mid_width: Some(Width {
                    value_m: state.mid_width_m,
                    scale_m: 0.001,
                }),
            });
        }
        sources.insert(id.into(), Source {
            reference: format!("test:synthetic-clamped-strip/{id}"),
            accessed_on: "2026-10-21".into(),
            note: "Generated by the production strip solver from [300,180,0.2,70] in crates/ftx-drape/examples/strip_fixture.rs. Numerical software data; CHECK is a separate computation, not an independent physical replicate. No measured textile or empirical validation claim.".into(),
        });
        experiments.push(Experiment {
            id: id.into(),
            fixture,
            source: id.into(),
            evidence: Evidence::Estimate,
            partition,
            observations,
        });
    }
    let input = Input {
        schema: "ftx-strip-calibration/1".into(),
        material: Material {
            id: "synthetic-identified-strip".into(),
            name: "Synthetic inverse strip software example, not a real textile".into(),
            form: Form::Sheet,
            composition: Vec::new(),
            composition_complete: false,
            structure: BTreeMap::new(),
            properties: BTreeMap::new(),
            membrane_response: None,
            membrane_relaxation: None,
            thermal_response: None,
            optical_faces: None,
            sources,
        },
        method: "Synthetic ideal full-width no-slip planar grips; 100 mm gauge, 60 mm width, independent elastic loading states; no actual specimen or conditioning".into(),
        conditions: BTreeMap::from([
            ("provenance".into(), "Synthetic solver-generated software example; no empirical observations".into()),
            ("known_parameters".into(), "[warp N/m,weft N/m,major Poisson ratio,shear N/m]=[300,180,0.2,70]".into()),
            ("weighting".into(), "0.1 N and 0.001 m are chosen numerical residual scales, not measurement uncertainty".into()),
        ]),
        fitted_on: "2026-10-21".into(),
        experiments,
        parameter_bounds: vec![[200.0, 400.0], [100.0, 260.0], [0.05, 0.35], [40.0, 100.0]],
        response_family: None,
        nonlinear: None,
        area_response: None,
        admit_planar_elastic_model: true,
        allow_estimated_observations: true,
        replace_existing: false,
        allow_estimates: true,
        controls,
        policy: Policy {
            max_rms_scaled: 1.0,
            max_peak_scaled: 1.0,
            max_mesh_scaled: 1.0,
            min_excitation_pivot: 1e-4,
            max_iterations: 40,
            max_forward_solves: 8000,
        },
    };
    println!("{}", serde_json::to_string_pretty(&input)?);
    Ok(())
}
