//! Generate nonlinear strip observations through the public production experiment.
//! `cargo run -p ftx-drape --example strip_nonlinear_fixture > NEW-REQUEST.json`
//! Shapes, forces and widths are synthetic; CHECK is not a physical replicate.

use std::collections::BTreeMap;

use ftx_drape::strip::{
    Request, evaluate,
    fit::{
        Input, Observation, Width,
        family::{Family, MODEL},
    },
};
use ftx_pattern::{
    material_calibration::Partition,
    material_catalog::Selection,
    material_response::{Interpolation, StressCurve, TabulatedMembrane},
    materials::{Evidence, Quantity, Source},
};

const PARAMETERS: [f64; 4] = [1.1, 0.9, 1.2, 40.0];

fn main() -> Result<(), Box<dyn std::error::Error>> {
    // Reuse only the declared fixtures, partitions and numerical controls of the scalar example.
    // Every response observation and every source description is replaced below.
    let mut input: Input = serde_json::from_str(include_str!(
        "../../../examples/strip-identification/synthetic-calibration.json"
    ))?;
    input.material.id = "synthetic-nonlinear-identified-strip".into();
    input.material.name = "Synthetic nonlinear strip identification, not a real textile".into();
    input.conditions = BTreeMap::from([
        ("provenance".into(), "Synthetic solver-generated software example; fixed nonlinear shapes are explicitly assumed and no physical observations are supplied".into()),
        ("known_parameters".into(), "[warp scale,weft scale,shear scale,normal coupling N/m]=[1.1,0.9,1.2,40]".into()),
        ("weighting".into(), "0.1 N and 0.001 m are chosen numerical residual scales, not measurement uncertainty".into()),
    ]);
    input.method = "Synthetic ideal no-slip planar grips; 100 mm free gauge and 60 mm width. Independent elastic loading states with the exact material-midpoint chord width. No measured textile, inferred curve shape or area-preserving term.".into();
    for (id, source) in &mut input.material.sources {
        source.reference = format!("test:synthetic-nonlinear-clamped-strip/{id}");
        source.note = "Generated by the production strip experiment in crates/ftx-drape/examples/strip_nonlinear_fixture.rs. Numerical observations; CHECK is a separate computation, not an independent physical replicate.".into();
    }
    input.material.sources.insert(
        "shape".into(),
        Source {
            reference: "test:synthetic-nonlinear-clamped-strip/declared-shapes".into(),
            accessed_on: "2026-10-21".into(),
            note: "Explicit synthetic signed piecewise-linear shapes, true dimensionless scales [1.1,0.9,1.2] and normal coupling 40 N/m. Model assumptions for software verification, not measurements or a recommended textile.".into(),
        },
    );
    let curve = |points: &[[f64; 2]]| {
        StressCurve {
        points: points.to_vec(),
        source: "shape".into(),
        evidence: Evidence::Estimate,
        method: "Declared synthetic piecewise-linear second-Piola resultant versus material Green strain; relative ordinates and signed branches are assumed, not fitted".into(),
        conditions: input.conditions.clone(),
    }
    };
    let family = Family {
        model: MODEL.into(),
        warp: curve(&[
            [-0.3, -90.0],
            [0.0, 0.0],
            [0.025, 7.5],
            [0.1, 45.0],
            [0.3, 185.0],
        ]),
        weft: curve(&[
            [-0.3, -60.0],
            [0.0, 0.0],
            [0.025, 5.0],
            [0.1, 27.5],
            [0.3, 107.5],
        ]),
        shear: curve(&[
            [-0.3, -24.0],
            [0.0, 0.0],
            [0.03, 2.4],
            [0.15, 14.4],
            [0.3, 38.4],
        ]),
        allow_estimated_shapes: true,
    };
    input.parameter_bounds = vec![[0.7, 1.5], [0.5, 1.3], [0.8, 1.6], [15.0, 65.0]];
    input.response_family = Some(family.clone());
    let mut truth = input.material.clone();
    let mut response = TabulatedMembrane {
        model: ftx_pattern::material_response::MODEL.into(),
        interpolation: Interpolation::PiecewiseLinear,
        area_response: None,
        warp: family.warp,
        weft: family.weft,
        shear: family.shear,
        coupling: Quantity {
            value: PARAMETERS[3],
            unit: "N/m".into(),
            evidence: Evidence::Estimate,
            source: "shape".into(),
            method: "Declared synthetic generating coupling; not a measured property".into(),
            conditions: input.conditions.clone(),
            bounds: None,
        },
    };
    for (curve, scale) in [&mut response.warp, &mut response.weft, &mut response.shear]
        .into_iter()
        .zip(PARAMETERS[..3].iter().copied())
    {
        for point in &mut curve.points {
            point[1] *= scale;
        }
    }
    truth.membrane_response = Some(response);
    let material = Selection {
        id: truth.id.clone(),
        record: Some(truth),
        allow_estimates: true,
        ..Selection::default()
    };
    for experiment in &mut input.experiments {
        let extensions = if experiment.partition == Partition::Fit {
            vec![0.02, 0.06, 0.1]
        } else {
            vec![0.04]
        };
        let report = evaluate(&Request {
            schema: "ftx-strip-experiment/1".into(),
            material: material.clone(),
            fixture: experiment.fixture.clone(),
            extensions,
            controls: input.controls.clone(),
        })?;
        experiment.observations = report
            .states
            .into_iter()
            .enumerate()
            .map(|(i, state)| Observation {
                id: format!("{}-nonlinear-{i}", experiment.id),
                extension_fraction: state.extension_fraction,
                force_n: state.force_n,
                scale_n: 0.1,
                mid_width: Some(Width {
                    value_m: state.mid_width_m,
                    scale_m: 0.001,
                }),
                extensometers: vec![],
            })
            .collect();
    }
    println!("{}", serde_json::to_string_pretty(&input)?);
    Ok(())
}
