"""Local, optional OpenCV adapter. Only IDs/pixels cross into the Rust measurement core.

Wire input: one JSON header line followed by exactly width*height*3 opaque BGR bytes.
The CLI owns decoding/orientation/input receipts; this process never reopens a photograph.
Wire output: one JSON document, including on failure. No homography or measurement is fitted here.
"""

import json
import math
import sys


def board_spec(sheet):
    if not isinstance(sheet, dict) or sheet.get("schema") != "fabric-calib-sheet/1":
        raise ValueError("expected a fabric-calib-sheet/1 sidecar from ftx measure calib-sheet")
    b = sheet.get("board")
    if not isinstance(b, dict) or b.get("type") != "charuco":
        raise ValueError("sheet.board.type must be charuco")
    allowed = {"type", "dictionary", "squares_x", "squares_y", "square_mm", "marker_mm",
               "legacy_pattern", "origin_mm", "origin_px", "size_mm", "size_px", "png_scale", "frame"}
    if set(b) - allowed:
        raise ValueError("unsupported board fields: " + ", ".join(sorted(set(b) - allowed)))
    # The sheet generator pins this dictionary and sequential marker IDs. Never substitute one.
    if b.get("dictionary") != "DICT_4X4_50":
        raise ValueError("unsupported dictionary; use the DICT_4X4_50 sheet generated by ftx")
    for key in ("squares_x", "squares_y"):
        if type(b.get(key)) is not int or not 3 <= b[key] <= 64:
            raise ValueError(key + " must be an integer in 3..=64")
    sx, sy = b["squares_x"], b["squares_y"]
    if sx * sy // 2 > 50 or (sx - 1) * (sy - 1) > 512:
        raise ValueError("board exceeds dictionary/corner capacity")
    for key in ("square_mm", "marker_mm"):
        if type(b.get(key)) not in (int, float) or not math.isfinite(b[key]) or b[key] <= 0:
            raise ValueError(key + " must be finite and positive")
    if not b["marker_mm"] < b["square_mm"] <= 1000:
        raise ValueError("require 0 < marker_mm < square_mm <= 1000")
    legacy = b.get("legacy_pattern", False)  # spec A.9 defaults to the non-legacy board
    if type(legacy) is not bool:
        raise ValueError("legacy_pattern must be a boolean")
    origin = b.get("origin_mm", [0.0, 0.0])
    if (not isinstance(origin, list) or len(origin) != 2
            or any(type(x) not in (int, float) or not math.isfinite(x) for x in origin)):
        raise ValueError("origin_mm must be two finite numbers")
    if "size_mm" in b:
        size = b["size_mm"]
        expected = [sx * b["square_mm"], sy * b["square_mm"]]
        if (not isinstance(size, list) or len(size) != 2
                or any(type(x) not in (int, float) or not math.isfinite(x)
                       or abs(x - y) > 1e-6 for x, y in zip(size, expected))):
            raise ValueError("size_mm disagrees with square_mm and board dimensions")
    if sheet.get("paper") not in ("letter", "a4"):
        raise ValueError("sheet.paper must be letter or a4")
    return b, legacy, origin


def detect(header, pixels):
    b, legacy, origin = board_spec(header.get("sheet"))
    if header.get("schema") != "ftx-charuco-request/1":
        raise ValueError("unsupported detector request")
    size = header.get("image_size_px")
    if (not isinstance(size, list) or len(size) != 2
            or any(type(x) is not int or not 2 <= x <= 1_000_000 for x in size)
            or size[0] * size[1] > 16_000_000):
        raise ValueError("invalid or oversized image_size_px")
    w, h = size
    if len(pixels) != w * h * 3:
        raise ValueError("BGR input length disagrees with image_size_px")
    try:
        import cv2
        import numpy as np
    except ImportError as exc:
        raise RuntimeError("OpenCV unavailable: install opencv-python-headless==4.13.0.92 "
                           "in the --detector-python environment") from exc
    if not hasattr(cv2, "aruco") or not hasattr(cv2.aruco, "CharucoDetector"):
        raise RuntimeError("OpenCV lacks CharucoDetector; install opencv-python-headless==4.13.0.92")
    cv2.setNumThreads(1)
    cv2.ocl.setUseOpenCL(False)
    aruco = cv2.aruco
    dictionary = aruco.getPredefinedDictionary(aruco.DICT_4X4_50)
    board = aruco.CharucoBoard((b["squares_x"], b["squares_y"]),
                              b["square_mm"], b["marker_mm"], dictionary)
    board.setLegacyPattern(legacy)
    params = aruco.DetectorParameters()
    params.minMarkerPerimeterRate = 0.01
    # Refine missing markers, not marker corner pixels next to the black chessboard cells.
    params.cornerRefinementMethod = aruco.CORNER_REFINE_NONE
    charuco = aruco.CharucoParameters()
    charuco.minMarkers = 2
    charuco.tryRefineMarkers = True
    gray = cv2.cvtColor(np.frombuffer(pixels, np.uint8).reshape(h, w, 3), cv2.COLOR_BGR2GRAY)
    corners, ids, marker_corners, marker_ids = aruco.CharucoDetector(
        board, charuco, params).detectBoard(gray)
    markers = [] if marker_ids is None else [int(x) for x in marker_ids.ravel()]
    if len(set(markers)) != len(markers):
        raise ValueError("AMBIGUOUS_BOARD: duplicate marker IDs; show only one calibration board")
    if any(x < 0 or x >= len(board.getIds()) for x in markers):
        raise ValueError("BOARD_MISMATCH: detected marker IDs do not belong to this sidecar")
    detections = []
    if ids is not None:
        if corners is None or len(corners) != len(ids):
            raise ValueError("inconsistent OpenCV corner arrays")
        # Explicitly refine chessboard corners, never ArUco marker vertices. Some OpenCV
        # versions leave interpolated corners at integer pixels with CORNER_REFINE_NONE.
        # Keep the window away from nearby marker cells on small/distant boards.
        vertices = np.concatenate(marker_corners).reshape(-1, 2)
        for corner in corners:
            distance = float(np.linalg.norm(vertices - corner.reshape(1, 2), axis=1).min())
            window = min(5, max(1, int(distance / 2)))
            cv2.cornerSubPix(gray, corner.reshape(1, 1, 2), (window, window), (-1, -1),
                             (cv2.TERM_CRITERIA_EPS | cv2.TERM_CRITERIA_MAX_ITER, 30, 0.001))
        detections = sorted((int(i), [float(x) for x in p])
                            for i, p in zip(ids.ravel(), corners.reshape(-1, 2)))
    if len(detections) > 512 or len({i for i, _ in detections}) != len(detections):
        raise ValueError("invalid or duplicate ChArUco corner IDs")
    total = (b["squares_x"] - 1) * (b["squares_y"] - 1)
    if any(i < 0 or i >= total or any(not math.isfinite(x) or not 0 <= x <= limit - 1
                                    for x, limit in zip(p, size)) for i, p in detections):
        raise ValueError("detected corners outside the board or oriented image")
    reference = {
        "schema": "ftx-photo-reference/1", "reference": "charuco",
        "image_size_px": size, "paper": header["sheet"]["paper"],
        "board": {"squares_x": b["squares_x"], "squares_y": b["squares_y"],
                  "square_mm": b["square_mm"], "origin_mm": origin},
        "corners": [{"id": i, "point_px": p} for i, p in detections],
        "markers_detected": len(markers),
    }
    return {"schema": "ftx-charuco-detection/1", "reference": reference,
            "detector": {"backend": "opencv_charuco", "opencv_version": cv2.__version__,
                         "dictionary": b["dictionary"], "legacy_pattern": legacy,
                         "marker_ids": sorted(markers), "min_marker_perimeter_rate": 0.01,
                         "min_markers_per_corner": 2, "refine_markers": True,
                         "chessboard_refinement": "adaptive_cornerSubPix",
                         "threads": 1, "coordinate_frame": "stored_full_resolution_pixels"}}


def main():
    try:
        line = sys.stdin.buffer.readline(65537)
        if len(line) > 65536 or not line.endswith(b"\n"):
            raise ValueError("detector header exceeds 64 KiB or is incomplete")
        header = json.loads(line)
        # Bounded even if called outside ftx. The CLI applies its own tighter photo budget.
        pixels = sys.stdin.buffer.read(48_000_001)
        result = detect(header, pixels)
    except Exception as exc:
        result = {"schema": "ftx-charuco-detection/1", "error": str(exc)}
    print(json.dumps(result, allow_nan=False, sort_keys=True, separators=(",", ":")))


if __name__ == "__main__":
    main()
